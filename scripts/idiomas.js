// 🔧 Función para cambiar idioma
function cambiarIdioma(idioma) {
    document.querySelectorAll('[data-i18n]').forEach(elemento => {
        const clave = elemento.getAttribute('data-i18n');
        if (traducciones[idioma] && traducciones[idioma][clave]) {
            if (elemento.tagName === 'INPUT' || elemento.tagName === 'TEXTAREA') {
                elemento.placeholder = traducciones[idioma][clave];
            } else {
                elemento.innerHTML = traducciones[idioma][clave];
            }
        }
    });
    localStorage.setItem('idiomaPreferido', idioma);
}

document.addEventListener('DOMContentLoaded', function () {
    const selector = document.getElementById('selectorIdioma');
    const idiomaGuardado = (localStorage.getItem('idiomaPreferido') || 'mx').toLowerCase();

    const opcionExiste = Array.from(selector.options).some(opt => opt.value === idiomaGuardado);
    selector.value = opcionExiste ? idiomaGuardado : 'mx';

    cambiarIdioma(selector.value);

    selector.addEventListener('change', function (e) {
        cambiarIdioma(e.target.value);
    });
});
